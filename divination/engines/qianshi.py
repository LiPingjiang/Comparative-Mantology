def zhijiao() -> str:
    """
    掷筊（擲筊 / 博杯）
    两个月牙形木块抛掷：
      - 圣杯（一阴一阳）: 概率 1/2 → 神明认可
      - 笑杯（双阳朝上）: 概率 1/4 → 神明在笑，再问
      - 阴杯（双阴朝上）: 概率 1/4 → 神明不认可
    """
    r = random.random()
    if r < 0.5:
        return "圣杯"
    elif r < 0.75:
        return "笑杯"
    else:
        return "阴杯"


def qiuqian() -> dict:
    """完整求签流程"""
    # 1. 摇签：从签筒中等概率抽取
    qian = random.choice(QIANSHI)

    # 2. 掷筊确认：需要连续三圣杯
    jiao_results = []
    confirmed = True
    for i in range(3):
        result = zhijiao()
        jiao_results.append(result)
        if result != "圣杯":
            confirmed = False
            break

    return {
        "签": qian,
        "掷筊": jiao_results,
        "确认": confirmed,
        "确认概率": "连续三圣杯概率 = (1/2)³ = 12.5%",
    }


def display(result: dict):
    """格式化显示"""
    print("\n" + "═" * 56)
    print("  签诗 · 庙签 · 求签问卦")
    print("═" * 56)

    qian = result["签"]
    print(f"\n  第{qian['num']}签  {qian['deng']}")
    print(f"  {qian['title']}\n")
    print(f"    {qian['poem']}\n")

    # 掷筊过程
    print("  掷筊确认：")
    for i, j in enumerate(result["掷筊"]):
        icons = {"圣杯": "🌓", "笑杯": "🌕", "阴杯": "🌑"}
        status = {"圣杯": "✓ 圣杯（一阴一阳）",
                  "笑杯": "✗ 笑杯（双阳）— 神明在笑",
                  "阴杯": "✗ 阴杯（双阴）— 不认可"}
        print(f"    第{i+1}筊：{icons.get(j, '')} {status[j]}")

    if result["确认"]:
        print(f"\n  ✅ 三圣杯确认！此签有效。")
        print(f"  解签：{qian['解']}")
    else:
        print(f"\n  ❌ 未获三圣杯，此签未被确认。")
        print(f"  传统做法：重新摇签再问。")

    print(f"\n  {result['确认概率']}")
    print()


