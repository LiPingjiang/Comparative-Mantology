def get_personality(blood_type: str) -> dict:
    """获取血型性格描述"""
    bt = blood_type.upper().strip()
    return BLOOD_TYPES.get(bt)


def get_compatibility(bt1: str, bt2: str) -> tuple[str, str]:
    """获取两个血型的相性"""
    bt1, bt2 = bt1.upper().strip(), bt2.upper().strip()
    key = (bt1, bt2) if (bt1, bt2) in COMPATIBILITY else (bt2, bt1)
    return COMPATIBILITY.get(key, ("?", "无数据"))


def display_personality(bt: str, info: dict):
    """显示单个血型性格"""
    print(f"\n  血型 {bt} 的性格描述：\n")
    for key, val in info.items():
        print(f"    {key}：{val}")


def interactive():
    """交互式血型性格"""
    print("\n╔══════════════════════════════════════╗")
    print("║   血型性格说 · 血液型性格判断       ║")
